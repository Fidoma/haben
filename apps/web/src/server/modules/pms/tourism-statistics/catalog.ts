export function tourismCountryKey(country: string | null | undefined): string {
  const code = country?.trim().toUpperCase();
  if (!code) return "not_specified";
  const isoCode = aliases[code] ?? code;
  if (direct[isoCode]) return direct[isoCode];
  return Object.entries(groups).find(([, codes]) => codes.includes(isoCode))?.[0] ?? "not_specified";
}
